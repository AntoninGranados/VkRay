namespace {
const bool registered = [] {
    ShaderPlugin::registerDispatchGenerator(&SkyTable::generateDispatch);
    return true;
}();
} // namespace

int SkyTable::slotFor(const std::filesystem::path& path) {
    static std::unordered_map<std::filesystem::path, int> slots;
    return GlslCodegen::slotFor(slots, path);
}

bool SkyTable::pack(ecs::Registry& registry, ecs::Entity environment, std::vector<float>& params) {
    if (environment == ecs::Entity{} || !registry.has(environment, ecs::SkyPlugin)) return false;

    ecs::Component& c = registry.get(environment, ecs::SkyPlugin);
    ShaderPlugin& plugin = c.payload<ShaderPlugin>("plugin");
    const std::filesystem::path path = c.get<std::filesystem::path>("path");
    plugin.parse(path, kType, kVersion, slotFor(path));
    if (!plugin.getError().empty()) return false;

    const std::vector<float> values = plugin.packValues();
    params.insert(params.end(), values.begin(), values.end());
    return true;
}

void SkyTable::generateDispatch() {
    ShaderPlugin* active = GlslCodegen::findActivePlugin(SkyTable::kType);

    std::string body =
        active ? std::format("// ============================= {} =============================\n"
                             "{}"
                             "{}"
                             "float3 dispatchSky(int base, float3 dir) {{\n"
                             "{}"
                             "float3 result = float3(0.1);\n"
                             "{}"
                             "return result;\n"
                             "}}\n",
                             SkyTable::kType, GlslCodegen::declareGlobals(*active), active->getDeclarations(),
                             GlslCodegen::assignParams(
                                 *active, [](int i) { return std::format("scene.pluginParams[base+{}]", i); }),
                             active->getBody())
               : "float3 dispatchSky(int base, float3 dir) {\n    return float3(0.1);\n}\n";

    std::string content = std::format(
        "// WARN: AUTO-GENERATED by SkyTable::generateDispatch, do not edit by hand.\n"
        "// Source: the programmable sky script on the scene's Environment entity (see assets/environment/).\n"
        "import \"../core/scene.slang\";\n"
        "import \"../dsl_math_utils.slang\";\n\n"
        "{}",
        body);

    Resources::add("builtin:/shaders/generated/sky_dispatch.slang", std::move(content));
}
